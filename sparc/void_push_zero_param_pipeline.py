def optimize_pwc_limit(clean_data, merge_col):
    print("\n--- INITIATING DOMAIN M PWC MATHEMATICAL LOCK (LOG-SPACE) ---")
    g_obs = clean_data['g_obs'].values
    g_bar = clean_data['g_bar'].values

    # Objective: Minimize the RMS Scatter (dex) across all SPARC measurements (log-space optimization)
    def pwc_scatter_rms_log10(log10_a0):
        a0 = 10.0**log10_a0
        # PWC core formulation
        g_pred = g_bar * (1.0 + np.sqrt(a0 / g_bar))
        residuals = np.log10(g_obs) - np.log10(g_pred)
        return np.sqrt(np.mean(residuals**2))

    res = minimize_scalar(
        pwc_scatter_rms_log10,
        bounds=(-13.0, -8.0),
        method='bounded',
        options={'xatol': 1e-12}
    )

    best_a0 = 10.0**res.x
    final_rms_point = res.fun

    # Galaxy-Balanced RMS Calculation
    def calc_galaxy_rms(df):
        g_obs_gal = df['g_obs'].values
        g_bar_gal = df['g_bar'].values
        g_pred_gal = g_bar_gal * (1.0 + np.sqrt(best_a0 / g_bar_gal))
        res = np.log10(g_obs_gal) - np.log10(g_pred_gal)
        return np.sqrt(np.mean(res**2))

    galaxy_rms_vals = (
        clean_data
        .groupby(merge_col, group_keys=False)
        .apply(calc_galaxy_rms, include_groups=False)
    )
